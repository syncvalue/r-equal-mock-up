const BY_NAME = [...SURNAMES].sort((a, b) => b[0].length - a[0].length); // 長い姓を先に（「佐々木」を「佐」より先に）
const BY_KANA = [...SURNAMES].sort((a, b) => b[1].length - a[1].length);

const compact = (s) => String(s ?? '').trim();

// 「山田花子」→ ['山田', '花子']。空白があれば空白で、なければ辞書の姓で、辞書にもなければ2文字を姓として分ける
export function splitFullName(full) {
  const t = compact(full);
  const parts = t.split(/[\s　]+/).filter(Boolean);
  if (parts.length >= 2) return [parts[0], parts.slice(1).join('')];
  const hit = BY_NAME.find(([k]) => t.startsWith(k) && t.length > k.length);
  if (hit) return [hit[0], t.slice(hit[0].length)];
  return t.length >= 3 ? [t.slice(0, 2), t.slice(2)] : [t, ''];
}

// 「ヤマダハナコ」→ ['ヤマダ', 'ハナコ']。空白があれば空白で、姓の読みが分かれば（辞書・姓の漢字から）そこで、なければ姓名の文字数の比で、それも分からなければ、真ん中あたりで分ける
export function splitFullKana(kana, lastName = '', firstName = '') {
  const t = compact(kana);
  const parts = t.split(/[\s　]+/).filter(Boolean);
  if (parts.length >= 2) return [parts[0], parts.slice(1).join('')];
  const byLast = SURNAMES.find(([k]) => k === compact(lastName));
  if (byLast && t.startsWith(byLast[1]) && t.length > byLast[1].length) return [byLast[1], t.slice(byLast[1].length)];
  const hit = BY_KANA.find(([, r]) => t.startsWith(r) && t.length > r.length);
  if (hit) return [hit[1], t.slice(hit[1].length)];
  const ln = compact(lastName).length;
  const fn = compact(firstName).length;
  const cut = ln && fn ? Math.round((t.length * ln) / (ln + fn)) : Math.round(t.length / 2);
  return [t.slice(0, cut), t.slice(cut)];
}

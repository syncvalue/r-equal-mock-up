const PRODUCTS_BUILT = [];
let seq = 0;
Object.entries(CATALOG).forEach(([category, brands]) => {
  brands.forEach(([brand, brandAlias, models]) => {
    models.forEach(([model, base, variants, modelAlias]) => {
      const vs = variants.length ? variants : [['', 1]];
      vs.forEach(([variant, mult]) => {
        seq += 1;
        const b = base * mult;
        PRODUCTS_BUILT.push({
          id: `p${String(seq).padStart(4, '0')}`,
          category,
          brand,
          model,
          variant,
          name: [brand, model, variant].filter(Boolean).join(' '),
          aliases: [...brandAlias, ...modelAlias],
          range: { min: r1000(b * 0.6), max: r1000(b * 1.3) },
          history: { min: r1000(b * 0.72), max: r1000(b * 1.18), count: ((seq * 37) % 58) + 3 },
        });
      });
    });
  });
});

